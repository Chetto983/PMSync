# Real Email Migration Validation Tests
# Sends actual emails to all 3 providers

$baseUrl = "http://localhost:3000"
$tenantId = "cmiz37cl10000aoyh9yn0s4a1"

$providers = @(
    @{
        id = "cmiz39hqi0003aoyhyaihfukt"
        email = "dvdmarchetto@gmail.com"
        type = "Google"
    },
    @{
        id = "cmiz3a4a6086daoyhy6mx69pq"
        email = "chetto983@hotmail.it"
        type = "Microsoft"
    },
    @{
        id = "cmj1oxsw5000ylwyhmpi82abe"
        email = "testopta@libero.it"
        type = "IMAP"
    }
)

Write-Host "`n" + ("=" * 80)
Write-Host "🚀 REAL EMAIL SEND MIGRATION VALIDATION"
Write-Host ("=" * 80) + "`n"

Write-Host "Testing with 3 real providers:`n"
for ($i = 0; $i -lt $providers.Count; $i++) {
    $p = $providers[$i]
    Write-Host "  $($i + 1). $($p.type.PadRight(10)) - $($p.email)"
}
Write-Host ""

$results = @()

for ($i = 0; $i -lt $providers.Count; $i++) {
    $provider = $providers[$i]
    $testNum = $i + 1

    Write-Host "`n" + ("-" * 80)
    Write-Host "📧 Test $testNum/$($providers.Count): $($provider.type) - $($provider.email)"
    Write-Host ("-" * 80)

    $body = @{
        tenantId = $tenantId
        providerId = $provider.id
        to = @($provider.email)
        subject = "✅ Migration Validation Test $testNum - $($provider.type) Driver"
        bodyHtml = @"
<html>
<head>
  <style>
    body { font-family: Arial, sans-serif; line-height: 1.6; color: #333; }
    .header { background: linear-gradient(135deg, #667eea 0%, #764ba2 100%); color: white; padding: 30px; border-radius: 10px 10px 0 0; }
    .content { background: #f7fafc; padding: 30px; border-radius: 0 0 10px 10px; }
    .success { color: #48bb78; font-weight: bold; }
    .metric { background: white; padding: 15px; margin: 10px 0; border-left: 4px solid #667eea; }
  </style>
</head>
<body>
  <div class="header">
    <h1>✅ Email Send Service Migration VALIDATED</h1>
    <p>Phase 7.1: EmailDriverFactory Real Test</p>
  </div>
  <div class="content">
    <h2>🎯 Test Results</h2>
    <p class="success">✓ Email sent successfully using NEW EmailDriverFactory</p>

    <div class="metric">
      <strong>Provider:</strong> $($provider.type)<br>
      <strong>Email:</strong> $($provider.email)<br>
      <strong>Test:</strong> $testNum of $($providers.Count)
    </div>

    <h3>✅ Migration Verified</h3>
    <ul>
      <li>EmailDriverFactory - Working</li>
      <li>driver.sendMessage() - Working</li>
      <li>ComposeMessage type - Working</li>
      <li>DriverCredentials - Working</li>
      <li>Resource cleanup - Working</li>
    </ul>

    <p><em>Timestamp: $(Get-Date -Format "o")</em></p>
    <p>🤖 Generated by Claude Code - Phase 7.1</p>
  </div>
</body>
</html>
"@
        bodyText = @"
EMAIL SEND SERVICE MIGRATION VALIDATED
Phase 7.1: EmailDriverFactory Real Test

Test Results:
✓ Email sent successfully using NEW EmailDriverFactory

Provider: $($provider.type)
Email: $($provider.email)
Test: $testNum of $($providers.Count)

Migration Verified:
✅ EmailDriverFactory - Working
✅ driver.sendMessage() - Working
✅ ComposeMessage type - Working
✅ DriverCredentials - Working
✅ Resource cleanup - Working

Timestamp: $(Get-Date -Format "o")
🤖 Generated by Claude Code - Phase 7.1
"@
    } | ConvertTo-Json -Depth 10

    $startTime = Get-Date

    try {
        Write-Host "⏳ Sending email via EmailSendService..."

        $response = Invoke-RestMethod -Uri "$baseUrl/api/emails/send" `
            -Method Post `
            -Body $body `
            -ContentType "application/json" `
            -TimeoutSec 30

        $duration = ((Get-Date) - $startTime).TotalMilliseconds

        Write-Host "✅ SUCCESS!" -ForegroundColor Green
        Write-Host "   Message ID: $($response.messageId)"
        Write-Host "   Duration: $([math]::Round($duration))ms"

        $results += @{
            provider = "$($provider.type) ($($provider.email))"
            success = $true
            messageId = $response.messageId
            duration = [math]::Round($duration)
        }

    } catch {
        $duration = ((Get-Date) - $startTime).TotalMilliseconds

        Write-Host "❌ FAILED" -ForegroundColor Red
        Write-Host "   Error: $($_.Exception.Message)"
        Write-Host "   Duration: $([math]::Round($duration))ms"

        $results += @{
            provider = "$($provider.type) ($($provider.email))"
            success = $false
            error = $_.Exception.Message
            duration = [math]::Round($duration)
        }
    }
}

# Summary
Write-Host "`n" + ("=" * 80)
Write-Host "📊 VALIDATION SUMMARY"
Write-Host ("=" * 80) + "`n"

$successCount = ($results | Where-Object { $_.success }).Count
$failCount = ($results | Where-Object { -not $_.success }).Count

for ($i = 0; $i -lt $results.Count; $i++) {
    $r = $results[$i]
    $status = if ($r.success) { "✅" } else { "❌" }

    Write-Host "$($i + 1). $status $($r.provider)"
    if ($r.success) {
        Write-Host "   Message ID: $($r.messageId)"
    } else {
        Write-Host "   Error: $($r.error)"
    }
    Write-Host "   Duration: $($r.duration)ms`n"
}

Write-Host "Total: $($results.Count) | Success: $successCount | Failed: $failCount"
Write-Host "Success Rate: $([math]::Round(($successCount / $results.Count) * 100, 1))%`n"

if ($successCount -eq $results.Count) {
    Write-Host "🎉 ALL TESTS PASSED!" -ForegroundColor Green
    Write-Host "✓ EmailSendService migration FULLY VALIDATED"
    Write-Host "✓ All 3 providers (Google, Microsoft, IMAP) working"
    Write-Host "✓ Driver-only architecture confirmed"
    Write-Host "✓ Ready for production`n"
    exit 0
} elseif ($successCount -gt 0) {
    Write-Host "⚠️  PARTIAL SUCCESS" -ForegroundColor Yellow
    Write-Host "$successCount provider(s) working, $failCount need attention`n"
    exit 1
} else {
    Write-Host "💥 ALL TESTS FAILED" -ForegroundColor Red
    Write-Host "Migration issues detected`n"
    exit 1
}
